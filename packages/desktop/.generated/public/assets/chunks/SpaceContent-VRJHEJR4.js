var validateDroppedFiles = (files, acceptedTypes, maxSize) => {
  const invalidTypes = [];
  const oversizedFiles = [];
  const validFiles = [];
  for (const file of files) {
    const fileExt = "." + file.name.split(".").pop()?.toLowerCase();
    const mimeType = file.type;
    const isExtValid = acceptedTypes.some((type) => {
      if (type.startsWith(".")) {
        return type.toLowerCase() === fileExt;
      }
      return false;
    });
    const isMimeValid = acceptedTypes.some((type) => {
      if (type.endsWith("/*")) {
        const prefix = type.replace("/*", "");
        return Boolean(mimeType && mimeType.startsWith(prefix));
      }
      if (type.includes("/")) {
        return type === mimeType;
      }
      return false;
    });
    if (!isExtValid && !isMimeValid) {
      invalidTypes.push(file.name);
      continue;
    }
    if (file.size > maxSize) {
      oversizedFiles.push(file.name);
      continue;
    }
    validFiles.push(file);
  }
  return {
    validFiles,
    invalidTypes,
    oversizedFiles
  };
};

export const MENU_USAGE_INSTRUCTIONS = `--- 交互说明 ---
所有用户输入均为纯文本消息，直接理解即可，不要在回复中提及按钮、菜单、界面等 UI 元素。

## 何时调用 ask_user
默认直接行动：能基于现有上下文给出高质量答案时就直接做，不要为了问而问；用户目标已具体清晰时，即便形式上满足下列条件也优先直接回答，不强行弹菜单。仅三种情况调用：1）需求宽泛或模糊，给出 2～5 个互斥且都合理的方向让用户先选；2）计划到达真正的分支节点——不同选择会显著改变成本、隐私或结果走向，且无法从上下文推断用户偏好；3）新会话开头需要按用户画像做功能导航或引导。

## 调用规范
- 先在普通回复文本里写清背景、理由与权衡再调用工具；无明确推荐项时，必须逐个简述选项优缺点帮助权衡；
- 有推荐方向就把该项放 choices 首位并标 recommended: true；
- 选项只承载适度信息：label 为短句、detail 至多一句话补充，userMessage 写成完整的下一句话；不在选项列表里放"其他/Other"（客户端会自动追加自由输入退路）；
- 问题写在 question 字段，不要在同一轮 assistant 普通文本里重复这句话（解释背景≠重复问题）。`;

/**
 * Progress suffix: ` · 12 tools · read, grep`. Empty when the run has not
 * reported any tool activity yet.
 */
function formatPanelProgress(snapshot: AgentRunSnapshot, now: number): string {
  const parts: string[] = [];
  // 工具信息存在时保持原样；纯推理 run（0 次工具调用）改用模型调用次数当心跳。
  const toolFact = formatToolProgressFact(snapshot);
  if (toolFact) parts.push(toolFact);
  // 停滞信号：事件计数不涨。
  const stallFact = formatStallFact(snapshot, now);
  if (stallFact) parts.push(stallFact);
  // 「此刻在做什么」压过「最后做过什么」——前者带自己的计时，看得出卡没卡住；
  // 后者只是历史。只有本地 registry 轮询报得出它。
  const inFlight = activeInFlight(snapshot);
  if (inFlight) {
    parts.push(formatInFlightFact(inFlight, now));
  } else if (snapshot.lastToolNames && snapshot.lastToolNames.length > 0) {
    parts.push(snapshot.lastToolNames.join(", "));
  }
  return parts.length > 0 ? ` · ${parts.join(" · ")}` : "";
}

/**
 * The run's own words beat its stdout. `lastAssistantText` is a sentence the
 * sub-agent wrote; the log tail is whatever byte sequence happened to land last
 * and is regularly a truncated JSON fragment.
 */
function formatPanelDetail(snapshot: AgentRunSnapshot): string {
  const note = snapshot.lastAssistantText?.trim();
  if (note) return note;
  // The log fallback obeys the same rule as the cards (`runShowsLogTail`)
  // rather than a second one of its own: raw stdout is evidence on a failed run
  // and noise on a healthy one.
  if (!runShowsLogTail(snapshot.status)) return "";
  const lines = snapshot.logLines;
  if (!lines || lines.length === 0) return "";
  return lines[lines.length - 1]?.trim() ?? "";
}

/**
 * agent 行的类型标记：用单列极简符号 ◈ 取代生硬的「agent / 智能体 / Sub-agent」类型字样与彩色 emoji。
 */
export const AGENT_TYPE_ICON = "◈";

/**
 * Internal run ids are useful diagnostics but poor primary UI. Prefer a real
 * agent name; auto-generated `agent-…` identities collapse to the stable
 * type marker. Detailed ids remain available in run cards/pro
 * output, just not in the dock's most prominent line.
 *
 * Exported because the multi-run dock row (`runDock.formatRunDockRow`) shows
 * the same identity in the same panel: collapsing only the single-run form
 * would put the raw generated id back on screen as soon as a second run docks.
 */
/**
 * Auto-generated identities that must never own the dock's primary line:
 *  - the private agent key `agent-<accountId>-<id|slug>`; the account id is the
 *    10-char hex slice produced by `generateUserIdV1`;
 *  - the public key form `agent-pub-<id>`;
 *  - run ids (`run-<ISO>-<rand>`, see `defaultGenerateRunId`), which the run
 *    label resolver can hand back when a record carries no name at all.
 * A human-authored display name has none of these shapes: `agent-security-check`
 * stays visible because its first segment is not an account id.
 */
const AUTO_IDENTITY_PATTERNS: readonly RegExp[] = [
  /^agent-[0-9a-f]{8,}-[a-z0-9]/i,
  /^agent-pub-[a-z0-9]{10,}$/i,
  /^run-\d{4}-\d{2}-\d{2}T[\d-]+Z-[a-z0-9]+$/i,
];

function isAutoGeneratedIdentity(raw: string): boolean {
  return AUTO_IDENTITY_PATTERNS.some((pattern) => pattern.test(raw));
}

/**
 * 运行行的身份解析顺序：真实名字 → 配置回读（显式 resolver，或已加载的
 * agent catalog/平台内置条目）→ agentKey 尾部短标识。
 *
 * 绝不退回通用的「subagent / 子智能体」标签：老记录（只有 agentKey、没有
 * agentName）也必须显示得出可区分的东西。
 *
 * `fallback` 留给自行渲染类型图标的调用方（面板 / runZone 自带 🤖）：它们
 * 已经承担了类型标记，不希望再降级出短键时才传；不传则按短键兜底。
 */
export type AgentNameResolver = (key: string) => string | undefined;

export function displayAgentName(
  snapshot: AgentRunSnapshot,
  resolveOrOptions?: AgentNameResolver | { fallback?: string },
): string {
  const resolveConfigName =
    typeof resolveOrOptions === "function" ? resolveOrOptions : undefined;
  const fallback =
    typeof resolveOrOptions === "function" ? undefined : resolveOrOptions?.fallback;
  const raw = snapshot.agentName?.trim();
  const isAuto = raw ? isAutoGeneratedIdentity(raw) : false;
  if (raw && !isAuto) {
    return raw;
  }
  const key = (snapshot.agentKey?.trim() || (isAuto ? raw : undefined) || "")?.trim();
  if (key) {
    const configName = resolveConfigName?.(key) ?? lookupCachedAgentName(key);
    if (configName?.trim() && !isAutoGeneratedIdentity(configName.trim())) {
      return configName.trim();
    }
    return fallback ?? shortAgentKey(key);
  }
  return fallback ?? shortAgentKey(snapshot.runId || "");
}

export function formatAgentRunPanelLines(
  snapshot: AgentRunSnapshot,
  colorEnabled: boolean,
  now: number = Date.now(),
  resolveConfigName?: (key: string) => string | undefined,
): string[] {
  const lines: string[] = [];
  // 面板自带 🤖 前导图标，名字解析不到时降级为 agentKey 尾部短标识（不再打通用类型标记）。
  const name = displayAgentName(snapshot, resolveConfigName);
  const namePart = name ? ` ${name}` : "";
  const status = snapshot.status || "running";
  const title = snapshot.title?.trim();
  const titlePart = title ? ` · 「${title}」` : "";
  const statusWord = agentRunStatusWord(status);

  // Status vocabulary comes from the run store (`done`/`failed`/`timeout`/
  // `killed`/`cancelled`), not from a guessed list.
  const statusSymbol = getAgentRunStatusIcon(status);
  const statusColor = runStatusTone(status);

  const errPart = snapshot.errorMessage ? ` · ${snapshot.errorMessage}` : "";
  const unassignedFact = formatUnassignedFact(snapshot);
  const unassignedPart = unassignedFact ? ` · ${unassignedFact}` : "";
  const progressPart = formatPanelProgress(snapshot, now);
  const stalled = runProgressStalled(snapshot, now);
  const age = formatTerminalRunAge(snapshot, now);
  const agePart = age ? ` · ${age}` : "";
  const creditsPart =
    typeof snapshot.credits === "number" && Number.isFinite(snapshot.credits)
      ? ` · ${formatCreditsChip(snapshot.credits)}`
      : "";

  if (!colorEnabled) {
    lines.push(
      `${AGENT_TYPE_ICON}${namePart}${titlePart} · ${statusSymbol} ${statusWord}${unassignedPart}${agePart}${progressPart}${creditsPart}${errPart}`
    );
  } else {
    const botIcon = themeText(AGENT_TYPE_ICON, "accent", true);
    const nameText = namePart ? themeText(namePart, "chrome", true) : "";
    const titleText = titlePart ? themeText(titlePart, "chrome", true) : "";
    const statusText = themeText(` · ${statusSymbol} ${statusWord}`, statusColor, true);
    const unassignedText = unassignedPart ? themeText(unassignedPart, "muted") : "";
    const ageText = agePart ? themeText(agePart, "chrome") : "";
    const progressText = progressPart
      ? themeText(progressPart, stalled ? "warning" : "chrome")
      : "";
    const creditsText = creditsPart ? themeText(creditsPart, "muted") : "";
    const errorText = errPart ? themeText(errPart, "danger") : "";
    lines.push(`${botIcon}${nameText}${titleText}${statusText}${unassignedText}${ageText}${progressText}${creditsText}${errorText}`);
  }

  const detail = formatPanelDetail(snapshot);
  if (detail) {
    if (!colorEnabled) {
      lines.push(`   └ ${detail}`);
    } else {
      lines.push(`${themeText("   └ ", "muted")}${themeText(detail, "chrome")}`);
    }
  }

  return lines;
}

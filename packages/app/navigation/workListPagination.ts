/**
 * Navigation V2 Work-page accumulation.
 * The cursor is an opaque *listing* cursor returned by a query adapter; NEVER
 * reuse useUserData's incremental synchronization cursor here.
 *
 * This module owns only merging/query identity. Authorization, sorting and
 * cursor generation belong to the server/data adapter.
 */
export interface WorkListQuery {
  userId: string;
  scope: "all" | { spaceId: string } | { projectId: string };
  order: "activity-desc";
  pageSize: number;
}
export interface WorkListRecord {
  dialogKey: string;
  updatedAt: number;
  spaceId?: string | null;
  projectId?: string | null;
}
export interface WorkListPage {
  records: readonly WorkListRecord[];
  /** null means exhausted; cursor must be generated by the same query endpoint. */
  nextCursor: string | null;
}
export interface WorkListState {
  queryKey: string;
  records: WorkListRecord[];
  nextCursor: string | null;
  loaded: boolean;
}
export function workListQueryKey(query: WorkListQuery): string {
  return JSON.stringify([query.userId, query.scope, query.order, query.pageSize]);
}
export function emptyWorkListState(query: WorkListQuery): WorkListState {
  return { queryKey: workListQueryKey(query), records: [], nextCursor: null, loaded: false };
}
/**
 * Reject late pages from a superseded scope; avoid cross-Workspace/Space leakage
 * when the user changes a filter while a request is in flight.
 */
export function appendWorkListPage(
  state: WorkListState,
  query: WorkListQuery,
  page: WorkListPage,
): WorkListState {
  if (state.queryKey !== workListQueryKey(query)) return state;
  const map = new Map<string, WorkListRecord>();
  for (const record of state.records) map.set(record.dialogKey, record);
  for (const record of page.records) {
    if (!record.dialogKey) continue;
    const previous = map.get(record.dialogKey);
    if (!previous || record.updatedAt >= previous.updatedAt) {
      map.set(record.dialogKey, record);
    }
  }
  return {
    queryKey: state.queryKey,
    records: [...map.values()].sort((a, b) => b.updatedAt - a.updatedAt || a.dialogKey.localeCompare(b.dialogKey)),
    nextCursor: page.nextCursor,
    loaded: true,
  };
}

/**
 * Merge a bounded local/hydrated dialog window with independently paged
 * history. This is a presentation union, not proof that history is complete.
 * Keep most-recent row per canonical key; do not infer access from the key.
 * Callers must supply only identity-authorized records.
 */
export function mergeWorkHistory(
  cached: readonly WorkListRecord[],
  paged: readonly WorkListRecord[],
): WorkListRecord[] {
  const map = new Map<string, WorkListRecord>();
  for (const record of [...cached, ...paged]) {
    if (!record.dialogKey) continue;
    const previous = map.get(record.dialogKey);
    if (!previous || record.updatedAt >= previous.updatedAt) {
      map.set(record.dialogKey, record);
    }
  }
  return [...map.values()].sort((a, b) =>
    b.updatedAt - a.updatedAt ||
    (a.dialogKey < b.dialogKey ? -1 : a.dialogKey > b.dialogKey ? 1 : 0));
}

/** Normalize public summary records after an authorized owned-page response. */
export function workRowsFromOwnedSummaries(
  summaries: readonly {
    dbKey?: string; contentKey?: string;
    updatedAt?: string | number; spaceId?: string | null;
  }[],
): WorkListRecord[] {
  const rows: WorkListRecord[] = [];
  for (const summary of summaries) {
    const dialogKey = summary.contentKey || summary.dbKey;
    if (!dialogKey || !dialogKey.startsWith("dialog-")) continue;
    const raw = summary.updatedAt;
    const updatedAt = typeof raw === "number" ? raw :
      typeof raw === "string" ? (Number.isFinite(Number(raw)) ? Number(raw) : Date.parse(raw)) : NaN;
    rows.push({ dialogKey, updatedAt: Number.isFinite(updatedAt) ? updatedAt : 0,
      spaceId: summary.spaceId ?? null });
  }
  return rows;
}
